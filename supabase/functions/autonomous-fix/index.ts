import { serve } from "https://deno.land/std@0.168.0/http/server.ts";
import { createClient } from "https://esm.sh/@supabase/supabase-js@2";
import {
  corsResponse,
  optionsResponse,
} from "../_shared/cors.ts";
import {
  getUserIdFromRequest,
  serviceClient,
} from "../_shared/auth.ts";
import { callNVIDIA, extractJson } from "../_shared/ai.ts";
import { decrypt } from "../_shared/crypto.ts";
import { fetchPrDiff } from "../_shared/github.ts";

const SYSTEM_PROMPT = `You are an autonomous AI software engineer. Analyze the PR diff and return JSON with specific code fixes.

Required schema:
{
  "fixes": [
    {
      "file": "<path>",
      "line": <number>,
      "issue": "<description>",
      "severity": "critical|high|medium|low",
      "category": "security|performance|bug|style",
      "original_code": "<exact current code>",
      "fixed_code": "<corrected code>",
      "confidence": <0-100>,
      "auto_applicable": <boolean>
    }
  ],
  "summary": "<2 sentence summary>",
  "breaking_changes": <boolean>,
  "tests_required": <boolean>
}

Only suggest fixes with confidence > 70%. Be precise with exact code snippets.`;

serve(async (req) => {
  if (req.method === "OPTIONS") return optionsResponse();
  if (req.method !== "POST") {
    return corsResponse({ error: "Method not allowed" }, { status: 405 });
  }

  try {
    const userId = await getUserIdFromRequest(req);
    const admin = serviceClient();
    const { repo_id, pr_number } = await req.json();

    // Get repo
    const { data: repo } = await admin
      .from("repositories")
      .select("*")
      .eq("id", repo_id)
      .eq("user_id", userId)
      .single();
    if (!repo) {
      return corsResponse({ error: "Repository not found" }, { status: 404 });
    }

    // Get GitHub token
    const { data: creds } = await admin
      .from("github_credentials")
      .select("encrypted_token")
      .eq("user_id", userId)
      .single();
    if (!creds?.encrypted_token) {
      return corsResponse({ error: "GitHub not connected" }, { status: 400 });
    }
    const token = await decrypt(creds.encrypted_token);

    // Create autonomous fix record
    const { data: fixRecord } = await admin
      .from("autonomous_fixes")
      .insert({
        user_id: userId,
        repo_id,
        pr_number,
        status: "analyzing",
        confidence_score: 0,
        issues_found: 0,
        fixes_applied: 0,
      })
      .select()
      .single();

    // Fetch PR diff
    const [owner, repoName] = repo.repo_name.split("/");
    const { pr, diffContext } = await fetchPrDiff(
      owner,
      repoName,
      String(pr_number),
      token
    );

    // Analyze with AI
    const result = await callNVIDIA(SYSTEM_PROMPT, diffContext, {
      temperature: 0.1,
      maxTokens: 6000,
      expectedJson: true,
    });

    const parsed = extractJson(result.content);
    const fixes = parsed.fixes ?? [];
    const highConfidenceFixes = fixes.filter((f: any) => f.confidence >= 70);

    // Update record
    await admin
      .from("autonomous_fixes")
      .update({
        status: "fixing",
        issues_found: fixes.length,
        fixes_applied: highConfidenceFixes.length,
        confidence_score: Math.round(
          fixes.reduce((sum: number, f: any) => sum + (f.confidence || 0), 0) /
            Math.max(fixes.length, 1)
        ),
      })
      .eq("id", fixRecord.id);

    // Post fix comments to GitHub PR
    for (const fix of highConfidenceFixes) {
      await fetch(
        `https://api.github.com/repos/${owner}/${repoName}/issues/${pr_number}/comments`,
        {
          method: "POST",
          headers: {
            Authorization: `Bearer ${token}`,
            Accept: "application/vnd.github.v3+json",
            "Content-Type": "application/json",
            "User-Agent": "code-companion-ai",
          },
          body: JSON.stringify({
            body: `## 🤖 Autonomous Fix Detected\n\n**File:** ${fix.file}:${fix.line}\n**Issue:** ${fix.issue}\n**Severity:** ${fix.severity}\n**Confidence:** ${fix.confidence}%\n\n### Current Code:\n\`\`\`\n${fix.original_code}\n\`\`\`\n\n### Suggested Fix:\n\`\`\`\n${fix.fixed_code}\n\`\`\`\n\n---\n*Auto-generated by Code Companion AI Agent*`,
          }),
        }
      );
    }

    await admin
      .from("autonomous_fixes")
      .update({
        status: "completed",
        completed_at: new Date().toISOString(),
      })
      .eq("id", fixRecord.id);

    return corsResponse({
      fix_id: fixRecord.id,
      fixes_found: fixes.length,
      fixes_applied: highConfidenceFixes.length,
      summary: parsed.summary,
      breaking_changes: parsed.breaking_changes,
    });
  } catch (error: any) {
    console.error("autonomous-fix error:", error);
    return corsResponse(
      { error: error.message || "Internal error" },
      { status: 500 }
    );
  }
});
